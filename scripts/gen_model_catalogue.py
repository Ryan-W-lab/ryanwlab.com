def js_string(value):
    return json.dumps(value, ensure_ascii=False)


def build_js():
    lines = []
    for m in MODELS:
        kinds = ",".join('"%s"' % k for k in m["kinds"])
        lic = m.get("lic", m.get("lic_en"))
        lines.append("    { n:%s, org:%s, kinds:[%s], licText:%s," % (
            js_string(m["n"]), js_string(m["org"]), kinds, js_string(lic)))
        lines.append("      params:%s, ctx:%s, date:%s, tier:\"%s\"," % (
            js_string(m.get("params", "")), js_string(m.get("ctx", "")),
            js_string(m.get("date", "")), m["tier"]))
        lines.append("      b:%s," % js_string(m.get("b", "")))
        lines.append("      sizes:%s, gpu:%s," % (js_string(m.get("sizes", "")), js_string(m.get("gpu", ""))))
        lines.append("      source:%s }," % js_string(m["src"]))
    return "\n".join(lines)


def build_en_table():
    rows = []
    for m in MODELS:
        lic = m.get("lic_en", m.get("lic", ""))
        kinds = " · ".join(KIND_EN[k] for k in m["kinds"])
        rows.append(
            "            <tr>\n"
            "              <td><b>%s</b></td><td>%s</td><td>%s</td><td>%s</td>\n"
            "              <td>%s<br><span class=\"dim\">%s</span></td><td>%s</td>\n"
            "              <td class=\"g\">%s<br>%s</td><td>%s</td>\n"
            "            </tr>" % (
                m["n_en"], m["org_en"], kinds, lic,
                m.get("params_en", m.get("params", "")), m.get("ctx_en", m.get("ctx", "")),
                m.get("date", ""), m.get("sizes_en", m.get("sizes", "")), m.get("gpu_en", m.get("gpu", "")),
                TIER_EN[m["tier"]]))
    return "\n".join(rows)


def main():
    main_js = ROOT / "assets" / "js" / "main.js"
    text = main_js.read_text(encoding="utf-8")
    start = text.index("  const ARS = [")
    end = text.index("  ];\n", start) + len("  ];\n")
    text = text[:start] + "  const ARS = [\n" + build_js() + "\n  ];\n" + text[end:]
    main_js.write_text(text, encoding="utf-8")
    print(f"assets/js/main.js: {len(MODELS)} 个模型")

    en = ROOT / "en" / "index.html"
    html = en.read_text(encoding="utf-8")
    sec = html.index('<section class="block" id="models">')
    tb = html.index('<tbody id="tbl-local-body">', sec)
    te = html.index("</tbody>", tb)
    html = html[:tb] + '<tbody id="tbl-local-body">\n' + build_en_table() + "\n          " + html[te:]
    en.write_text(html, encoding="utf-8")
    print(f"en/index.html: {len(MODELS)} 行本地清单")


if __name__ == "__main__":
    main()
